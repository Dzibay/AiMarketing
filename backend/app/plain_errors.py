GENERIC = "что-то пошло не так. Попробуйте ещё раз позже"

_CYRILLIC = re.compile(r"[А-Яа-яЁё]")
# «(ошибка 58)», «Ошибка 8800.» — номер кода Директа человеку ничего не говорит.
_DIRECT_NUMBER = re.compile(r"\s*\((?:ошибка|код)\s*\d+\)|^\s*(?:ошибка|код)\s*\d+[.:]?\s*", re.I)


def _codes() -> dict[str, str]:
    from app.journal import _CODE_TEXTS

    return {**_CODE_TEXTS, **_EXTRA}


def _cap(text: str) -> str:
    text = text.strip().rstrip(".").strip()
    return text[:1].upper() + text[1:] if text else text


def plain_error(code: str | None, message: str | None = "") -> str:
    """Причина сбоя одной фразой по-русски, с заглавной, без точки в конце. Пустой код и текст — общая фраза."""
    code = str(code or "").strip()
    message = str(message or "").strip()
    if "|" in code and not message:
        code, message = (part.strip() for part in code.split("|", 1))
    if code:
        from app import ai

        if ai.is_provider_error(code):
            return _cap(ai.human_error(code, message, chat=False)[0])
    if code in ("internal", "crash", "stale"):
        # В тексте — str(исключения) или служебное «Воркер перестал отвечать»: это не для кабинета.
        return _cap(_EXTRA[code])
    if message and _CYRILLIC.search(message):
        cleaned = _DIRECT_NUMBER.sub("", message).strip(" .;")
        if cleaned:
            return _cap(cleaned)
    codes = {**_DIRECT_CODES, **_codes()}
    if code in codes:
        return _cap(codes[code])
    if " " in code and _CYRILLIC.search(code):
        return _cap(code)  # вместо кода записан уже текст
    return _cap(GENERIC)
